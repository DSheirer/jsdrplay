    private static ValueLayout u8(String name) {
        return JAVA_BYTE.withName(name);
    }

    private static Map<String, GroupLayout> byName(GroupLayout... layouts) {
        Map<String, GroupLayout> map = new LinkedHashMap<>();
        Arrays.stream(layouts).forEach(layout -> map.put(layout.name().orElseThrow(), layout));
        return Map.copyOf(map);
    }

    /** Returns the byte offset of a field, following a path of nested field names. */
    public static long offset(MemoryLayout layout, String... path) {
        return layout.byteOffset(Arrays.stream(path).map(MemoryLayout.PathElement::groupElement)
            .toArray(MemoryLayout.PathElement[]::new));
    }

    /** Reads a NUL-terminated string from a {@code char} array field of at most {@code length} bytes. */
    public static String string(MemorySegment segment, long offset, long length) {
        MemorySegment field = segment.asSlice(offset, length);
        long end = 0;
        while (end < length && field.get(JAVA_BYTE, end) != 0) {
            end++;
        }
        return new String(field.asSlice(0, end).toArray(JAVA_BYTE), StandardCharsets.UTF_8);
    }
